/**
 * Writes src/content/adelva-management-operations-geometry.ts from the adopted
 * B-hq prototypes (desktop and mobile). Every coordinate is a measurement the
 * prototypes already shipped with; nothing is re-measured here.
 *
 *   node scripts/adelva/build-management-operations-geometry.mjs
 *
 * Plate px refer to the 1536×8379 photograph. Desktop index positions are CSS
 * px of the 1440-wide prototype stage ("u"), as the prototype set them.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import vm from "node:vm";

const root = resolve(import.meta.dirname, "../..");
const mocks = resolve(root, "references/adelva/mockups");
const desktopDir = resolve(mocks, "management-operations-B-hq-2026-10-01");
const mobileDir = resolve(mocks, "management-operations-B-hq-mobile-2026-10-01");

const load = (file, name) => {
  const context = { window: {} };
  vm.runInNewContext(readFileSync(file, "utf8"), context);
  return context.window[name];
};

const desktop = load(resolve(desktopDir, "build/geometry.js"), "HQ_GEOMETRY");
const assets = load(resolve(desktopDir, "build/assets.js"), "HQ_ASSETS");
const mobile = load(resolve(mobileDir, "build/geometry.js"), "GEO");
const html = readFileSync(resolve(desktopDir, "build/index.html"), "utf8");

const round = (value, digits = 3) => +value.toFixed(digits);

/* Desktop index: the inline positions make-page.mjs wrote into the prototype. */
const themeBlocks = [...html.matchAll(/<li\s+class="theme"[\s\S]*?<\/ul>\s*<\/li>/g)];
if (themeBlocks.length !== 4)
  throw new Error(`expected 4 themes, got ${themeBlocks.length}`);
const desktopThemes = themeBlocks.map(([block]) => {
  const num = (pattern) => {
    const match = block.match(pattern);
    if (!match) throw new Error(`missing ${pattern} in theme block`);
    return round(Number(match[1]));
  };
  const titleSize = block.match(/<h3 style="[^"]*font-size:\s*([\d.]+)px/);
  return {
    theme: num(/data-theme="(\d)"/),
    lineLeft: num(/--theme-left:\s*([\d.]+)px/),
    lineWidth: num(/--theme-width:\s*([\d.]+)px/),
    titleX: num(/<h3 style="left:\s*([\d.]+)px/),
    titleSize: titleSize ? Number(titleSize[1]) : 32,
    services: Object.fromEntries(
      [...block.matchAll(/data-service="(\d+)" style="left:\s*([\d.]+)px"/g)].map(
        ([, id, x]) => [id, round(Number(x))],
      ),
    ),
  };
});

/* Comet paths: the mobile build's smoothed paths (every third desktop sample,
   12 plate px apart), shared by both regimes. */
const paths = desktop.services.map((service) => ({
  id: service.id,
  group: service.group,
  points: mobile.paths[service.id].d,
}));

const slice = (list) => list.map(({ name, y, height }) => ({ name, y, height }));
const layer = ({ name, x, y, width, height }) => ({ name, x, y, width, height });

const geometry = {
  plate: {
    width: desktop.plate.width,
    height: desktop.plate.height,
    /** Rows of generated sky above plate row 0 (mobile hero only). */
    sky: mobile.plate.sky,
    /** CSS px per plate px on the 1440-wide desktop stage. */
    cssScale: desktop.plate.cssScale,
    /** Desktop stage height in u (the plate's dark tail is cropped). */
    stageHeight: desktop.plate.displayHeightCSS,
  },
  slices: {
    base: slice(assets.slices.base),
    dim: slice(assets.slices.dim),
    lit: slice(assets.slices.lit),
    blur: slice(assets.slices.blur),
  },
  warm: {
    knuckles: assets.warmKnuckles.map(layer),
    old: assets.warmOld.map(layer),
    young: layer(assets.young),
  },
  trunks: mobile.trunks,
  paths,
  knuckles: desktop.knuckles.map((knuckle) => ({
    group: knuckle.group,
    center: knuckle.center,
  })),
  themeRanges: desktop.themeRanges,
  oldTrunk: {
    top: Math.min(...desktop.oldTrunk.polygon.map(([, y]) => y)),
    bottom: Math.max(...desktop.oldTrunk.polygon.map(([, y]) => y)),
  },
  desktopIndex: { themes: desktopThemes },
  mobileIndex: mobile.index,
  band2x: mobile.band2x,
};

const body = `/**
 * Photograph geometry of /services/management-operations (B 台杉「降りてくる朝」).
 *
 * Generated by scripts/adelva/build-management-operations-geometry.mjs from the
 * adopted B-hq prototypes; do not edit by hand. Plate px refer to the 1536×8379
 * photograph. \`desktopIndex\` positions are CSS px of the 1440-wide stage (u).
 */

type Point = readonly [number, number];
interface Slice {
  readonly name: string;
  readonly y: number;
  readonly height: number;
}
interface Layer {
  readonly name: string;
  readonly x: number;
  readonly y: number;
  readonly width: number;
  readonly height: number;
}

export interface MoGeometry {
  readonly plate: {
    readonly width: number;
    readonly height: number;
    readonly sky: number;
    readonly cssScale: number;
    readonly stageHeight: number;
  };
  readonly slices: Readonly<Record<"base" | "dim" | "lit" | "blur", readonly Slice[]>>;
  readonly warm: {
    readonly knuckles: readonly Layer[];
    readonly old: readonly Layer[];
    readonly young: Layer;
  };
  readonly trunks: readonly Point[];
  readonly paths: readonly {
    readonly id: string;
    readonly group: number;
    readonly points: readonly Point[];
  }[];
  readonly knuckles: readonly { readonly group: number; readonly center: Point }[];
  readonly themeRanges: readonly Point[];
  readonly oldTrunk: { readonly top: number; readonly bottom: number };
  readonly desktopIndex: {
    readonly themes: readonly {
      readonly theme: number;
      readonly lineLeft: number;
      readonly lineWidth: number;
      readonly titleX: number;
      readonly titleSize: number;
      readonly services: Readonly<Record<string, number>>;
    }[];
  };
  readonly mobileIndex: {
    readonly zoom: number;
    readonly hairlineY: number;
    readonly groups: readonly {
      readonly theme: number;
      readonly title: number;
      readonly services: Readonly<Record<string, number>>;
    }[];
    readonly light: readonly Point[];
  };
  readonly band2x: {
    readonly x: number;
    readonly y: number;
    readonly w: number;
    readonly h: number;
  };
}

export const moGeometry: MoGeometry = ${JSON.stringify(geometry)};
`;

const out = resolve(root, "src/content/adelva-management-operations-geometry.ts");
writeFileSync(out, body);
console.log({
  out,
  bytes: Buffer.byteLength(body),
  paths: paths.length,
  points: paths.reduce((sum, path) => sum + path.points.length, 0),
  themes: desktopThemes.map((theme) => Object.keys(theme.services).join(",")),
});
